    public NewCodeBuilder(INamedTypeSymbol type, List<IStepContext> stepContexts,
        SingleFormEvaluationContext singleFormEvaluationContext)
    {
        Type = type;
        StepContexts = stepContexts;
        SingleFormEvaluationContext = singleFormEvaluationContext;

        CanBeInitializedWithoutParameters = EvaluateIfCanBeInitalizedWithoutParameters();
        // A note about hasEmptyConstructor. If there are no empty constructors we will
        // instantiate the type so it's required to pass it in. So we remove the default value and
        // change the return type to be void or Task
    }

    public bool BuildPartialCode(out string partialCode)
    {
        partialCode = string.Empty;

        if (StepContexts.All(x => !x.GetConditionContext().IsPartial))
        {
            return false;
        }

        var builder = new StringBuilder().AppendLine(
            $"""
             // <auto-generated/>
             #pragma warning disable
             #nullable enable
             {BuildUsingStatements()}
             """);

        using (NamespaceScope.Begin(builder, Type.ContainingNamespace))
        {
            builder.AppendLine($"\tpublic partial class {Type.Name}")
                .AppendLine($"\t{{");

            foreach (var stepContext in StepContexts.Where(x => x.GetConditionContext().IsPartial))
            {
                var summaryBuilder = new SummaryLineWriter(builder);

                summaryBuilder.AppendLine("/// <summary>", false);
                stepContext.BuildContext.WriteToSummary(summaryBuilder);
                summaryBuilder.AppendLine("/// </summary>", false);

                MemberDeclarationSyntax syntax = stepContext switch
                {
                    MethodContext methodContext => methodContext.EvaluationContext.MethodSyntax,
                    PropertyContext propertyContext => (MemberDeclarationSyntax) propertyContext.PropertySymbol
                        .DeclaringSyntaxReferences[0].GetSyntax(),
                    _ => throw new ArgumentOutOfRangeException(nameof(stepContext))
                };

                if (syntax is PropertyDeclarationSyntax property)
                {
                    property = property.WithAccessorList(GenerateAccessor());
                    property = property.WithAttributeLists(default).WithoutLeadingTrivia();

                    if (property.Initializer != null)
                    {
                        property = property.WithInitializer(null).WithSemicolonToken(default);
                    }


                    builder.AppendLine(property.NormalizeWhitespace().ToFullString());
                }
                else if (syntax is MethodDeclarationSyntax method)
                {
                    method = method
                        .WithBody(null)
                        .WithExpressionBody(null)
                        .WithAttributeLists(default)
                        .WithModifiers(TokenList(method.Modifiers.Where(m => !m.IsKind(SyntaxKind.AsyncKeyword))))
                        .WithoutTrailingTrivia()
                        .WithSemicolonToken(Token(SyntaxKind.SemicolonToken));
                    builder.AppendLine(method.NormalizeWhitespace().ToFullString());
                }
            }

            builder.AppendLine("}");
        }

        partialCode = ParseCompilationUnit(builder.ToString()).NormalizeWhitespace().ToFullString();
        return true;
    }

    private AccessorListSyntax GenerateAccessor()
    {
        // Emit the contextual "field" keyword as text-compatible identifier syntax so the
        // generator itself can compile against Roslyn versions that predate FieldExpressionSyntax.
        return AccessorList
        (
            List<AccessorDeclarationSyntax>
            (
                new AccessorDeclarationSyntax[]
                {
                    AccessorDeclaration
                        (
                            SyntaxKind.GetAccessorDeclaration
                        )
                        .WithExpressionBody
                        (
                            ArrowExpressionClause
                            (
                                IdentifierName("field")
                            )
                        )
                        .WithSemicolonToken
                        (
                            Token(SyntaxKind.SemicolonToken)
                        ),
                    AccessorDeclaration
                        (
                            SyntaxKind.SetAccessorDeclaration
                        )
                        .WithExpressionBody
                        (
                            ArrowExpressionClause
                            (
                                AssignmentExpression
                                (
                                    SyntaxKind.SimpleAssignmentExpression,
                                    IdentifierName("field"),
                                    IdentifierName("value")
                                )
                            )
                        )
                        .WithSemicolonToken
                        (
                            Token(SyntaxKind.SemicolonToken)
                        )
                }
            )
        );
    }

    /// <summary>
    /// Helps create and fill <see cref="NewCodeBuilder"/> with values
    /// </summary>
    /// <returns>A string representation of the generated code</returns>
    public string BuildCode()
    {
        //{{ returnTypeName }}   Prompt{{ (isAsync ? "Async " : string.Empty) }}({{ typeName}} {{FormName}});


        // Gets the type name
        var typeName = Type.FullName();
        var name = $"{Type.ContainingNamespace}.{Type.FullName()}";

        var members = BuildStepContexts();
        var isAsync = IsAsync;
        var interfaceInheritance = isAsync
            ? $"IAsyncSpectreFactory<{typeName}>, ICancellableSpectreFactory<{typeName}>"
            : $"ISpectreFactory<{typeName}>, IAsyncSpectreFactory<{typeName}>, ICancellableSpectreFactory<{typeName}>";
        var implementationInheritance = isAsync
            ? $"AsyncSpectreFactoryBase<{typeName}>, {SpectreFactoryInterfaceName}"
            : $"{SpectreFactoryInterfaceName}";

        var returnTypeName = isAsync ? $"Task<{Type.FullName()}>" : Type.FullName();
        var cancellationMembers = BuildStepContexts(supportsCancellation: true);

        var builder = new StringBuilder();
        builder.AppendLine("""
                           // <auto-generated/>
                           #pragma warning disable
                           #nullable enable
                           """);
        builder.AppendLine(BuildUsingStatements());

        using (NamespaceScope.Begin(builder, Type.ContainingNamespace))
        {
            builder.AppendLine($$"""
                                 /// <summary>
                                 /// Helps create and fill <see cref="{{typeName}}"/> with values
                                 /// </summary>
                                 public interface {{SpectreFactoryInterfaceName}} : {{interfaceInheritance}}
                                 {
                                     {{BuildCompatibilityInterfaceMethods(typeName, isAsync)}}
                                 }

                                 /// <summary>
                                 /// Helps create and fill <see cref="{{typeName}}"/> with values
                                 /// </summary>
                                 public class {{SpectreFactoryClassName}} : {{implementationInheritance}}
                                 {
                                     /// <summary>Prompts for the form using the existing non-cancellable API.</summary>
                                     public {{(isAsync ? "override " : string.Empty)}}{{returnTypeName}}  Prompt{{(isAsync ? "Async " : string.Empty)}}({{typeName}} {{FormName}})
                                     {
                                         {{(isAsync ? $"return PromptAsync({FormName}, CancellationToken.None);" : $"if ({FormName} == null) throw new ArgumentNullException(nameof({FormName}));\n{PreInitalization()}\n{InitCulture()}\n{members}\nreturn {FormName};")}}
                                     }

                                     {{BuildCancellationMethods(typeName, isAsync, cancellationMembers)}}
                                 }

                                 {{string.Empty /* GenerateExtensionMethodsClass()*/ }}
                                 """);
        }

        return SyntaxFactory.ParseCompilationUnit(builder.ToString()).NormalizeWhitespace().ToFullString();
    }

    /// <summary>Emits an asynchronous path without changing existing method signatures.</summary>
    private string BuildCompatibilityInterfaceMethods(string typeName, bool isAsync)
    {
        return $$"""
                 {{(isAsync ? string.Empty : $"Task<{typeName}> IAsyncSpectreFactory<{typeName}>.PromptAsync({typeName} form) => Task.FromResult(((ISpectreFactory<{typeName}>)this).Prompt(form));")}}

                 /// <summary>Provides a cooperative fallback for existing implementations of this interface.</summary>
                 /// <remarks>Legacy implementations cannot be interrupted while their original prompt method runs.</remarks>
                 async Task<{{typeName}}> ICancellableSpectreFactory<{{typeName}}>.PromptAsync({{typeName}} form, CancellationToken cancellationToken)
                 {
                     cancellationToken.ThrowIfCancellationRequested();
                     var result = await ((IAsyncSpectreFactory<{{typeName}}>)this).PromptAsync(form).ConfigureAwait(false);
                     cancellationToken.ThrowIfCancellationRequested();
                     return result;
                 }
                 """;
    }

    /// <summary>Emits an asynchronous path without changing existing method signatures.</summary>
    private string BuildCancellationMethods(string typeName, bool isAsync, string members)
    {
        return $$"""
                 {{(isAsync ? string.Empty : $"/// <summary>Asynchronously prompts for the form without cancellation.</summary>\npublic Task<{typeName}> PromptAsync({typeName} {FormName}) => PromptAsync({FormName}, CancellationToken.None);")}}

                 /// <summary>Asynchronously populates the form, observing cancellation during prompts and between steps.</summary>
                 /// <remarks>Properties populated before cancellation are retained. Task steps must cooperate to interrupt their own work.</remarks>
                 public {{(isAsync ? "override " : string.Empty)}}async Task<{{typeName}}> PromptAsync({{typeName}} {{FormName}}, CancellationToken cancellationToken)
                 {
                     if ({{FormName}} == null) throw new ArgumentNullException(nameof({{FormName}}));
                     cancellationToken.ThrowIfCancellationRequested();
                     {{PreInitalization()}}
                     {{InitCulture()}}
                     {{members}}
                     cancellationToken.ThrowIfCancellationRequested();
                     return {{FormName}};
                 }
                 """;
    }

    private bool IsAsync
    {
        get
        {
            var isAsync = StepContexts.Any(x => x.IsAsync);
            return isAsync;
        }
    }

    private string SpectreFactoryClassName
    {
        get
        {
            var spectreFactoryClassName = Type.GetSpectreFactoryClassName();
            return spectreFactoryClassName;
        }
    }

    private string SpectreFactoryInterfaceName
    {
        get
        {
            var spectreFactoryInterfaceName = Type.GetSpectreFactoryInterfaceName();
            return spectreFactoryInterfaceName;
        }
    }


    private string TaskOrTypeName(string typeName, bool isAsync)
    {
        return isAsync ? $"System.Threading.Tasks.Task<{typeName}>" : typeName;
    }

