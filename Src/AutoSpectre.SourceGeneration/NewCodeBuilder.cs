    private string GetReturnedType(string type, bool isAsync)
    {
        return $"{(isAsync ? "async" : "")} {type}";
    }

    private string InitCulture()
    {
        var cultureInitializer = SingleFormEvaluationContext.ConfirmedCulture switch
        {
            { } cult => $"new CultureInfo(\"{cult.Culture}\")",
            _ => "CultureInfo.CurrentUICulture"
        };

        return $"var {CodeBuildConstants.CultureVariableName} = {cultureInitializer};";
    }

    private bool EvaluateIfCanBeInitalizedWithoutParameters()
    {
        if (SingleFormEvaluationContext.UsedConstructor == null)
            return false;

        return SingleFormEvaluationContext.UsedConstructor!.Parameters.Length == 0 &&
               !Type.GetAllProperties().Any(x => x.IsRequired);
    }

    private string PreInitalization()
    {
        var builder = new StringBuilder();

        foreach (var code in StepContexts.SelectMany(x => x.BuildContext.CodeInitializing()).Distinct())
        {
            builder.AppendLine(code);
        }

        return builder.ToString();
    }

    private string BuildUsingStatements()
    {
        var builder = new StringBuilder();
        foreach (var nmSpace in InitialNamespaces.Concat(StepContexts.SelectMany(x => x.BuildContext.Namespaces()))
                     .Distinct().Where(x => x != Type.ContainingNamespace.ToString()))
        {
            builder.AppendLine($"using {nmSpace};");
        }

        return builder.ToString();
    }

    private string BuildStepContexts(bool supportsCancellation = false)
    {
        StringBuilder builder = new();
        foreach (var stepContext in this.StepContexts)
        {
            ConfigureCancellation(stepContext.BuildContext, supportsCancellation);
            if (supportsCancellation)
            {
                builder.AppendLine("cancellationToken.ThrowIfCancellationRequested();");
            }

            void AddConditions(ConfirmedCondition condition)
            {
                var boolValue = condition.Negate ? "false" : "true";

                if (condition.SourceType == ConditionSource.Method)
                {
                    builder.AppendLine($"if ({FormName}.{condition.Condition}() == {boolValue})");
                }
                else if (condition.SourceType == ConditionSource.Property)
                {
                    builder.AppendLine($"if ({FormName}.{condition.Condition} == {boolValue})");
                }
                else
                {
                    throw new InvalidOperationException("Unexpected condition type");
                }


                builder.AppendLine("{");
                AddLine();
                builder.AppendLine("}");
            }

            void AddLine()
            {
                switch (stepContext)
                {
                    case MethodContext methodContext:
                        builder.AppendLine(
                            $"{methodContext.BuildContext.GenerateOutput($"{FormName}.{methodContext.MethodName}")}");
                        break;
                    case PropertyContext propertyContext:
                        builder.AppendLine(
                            $"{propertyContext.BuildContext.GenerateOutput($"{FormName}.{propertyContext.PropertyName}")}");
                        break;
                    default:
                        throw new ArgumentOutOfRangeException(nameof(stepContext));
                }
            }


            if (stepContext is PropertyContext {BuildContext.Context.ConfirmedCondition: { } confirmedCondition})
            {
                AddConditions(confirmedCondition);
            }
            else if (stepContext is MethodContext {EvaluationContext.ConfirmedCondition: { } confirmedMethodCondition})
            {
                AddConditions(confirmedMethodCondition);
            }
            else
            {
                AddLine();
            }
        }

        return builder.ToString();
    }

    /// <summary>Propagates the emission mode into prompts nested inside collection builders.</summary>
    private static void ConfigureCancellation(PromptBuildContext context, bool supportsCancellation)
    {
        context.SupportsCancellation = supportsCancellation;
        if (context is MultiAddBuildContext multiAdd)
        {
            ConfigureCancellation(multiAdd.BuildContext, supportsCancellation);
        }
    }

    public string BuildPartialSpectreFactory()
    {
        var containingUsing = Type.ContainingNamespace.IsGlobalNamespace
            ? string.Empty
            : $"using {Type.ContainingNamespace};";

        return $$"""
                 {{containingUsing}}

                 namespace AutoSpectre;

                 public static partial class SpectreFactory
                 {
                     {{
                         GenerateSpectreFactoryMethodInvocations()
                     }}
                 }

                 """;
    }

    private string GenerateSpectreFactoryMethodInvocations()
    {
        var builder = new StringBuilder();
        var typeName = Type.FullName();
        var typeNameWithUnderscore = typeName.Replace(".", "_");

        var getSpectreFactoryMethodName = $"GetSpectreFactory_{typeNameWithUnderscore}";

        var spectreInterfaceType = IsAsync ? $"IAsyncSpectreFactory<{typeName}>" : $"ISpectreFactory<{typeName}>";

        builder.AppendLine(
            $"public static {spectreInterfaceType} {getSpectreFactoryMethodName}() => new {SpectreFactoryClassName}();");

        var returnType = TaskOrTypeName(typeName, IsAsync);
        var methodName = IsAsync ? "PromptAsync" : "Prompt";

        var asyncString = IsAsync ? "async " : string.Empty;
        var awaitString = IsAsync ? "await " : string.Empty;

        if (CanBeInitializedWithoutParameters)
        {
            builder.AppendLine($"public static {asyncString} {returnType} {methodName}_{typeNameWithUnderscore}()");
            builder.AppendLine("{");
            builder.AppendLine($"\tvar result = new {typeName}();");
            builder.AppendLine($"\tvar factory = {getSpectreFactoryMethodName}();");
            builder.AppendLine($"\treturn {awaitString} factory.{methodName}(result);");
            builder.AppendLine("}");
        }
        else
        {
            builder.AppendLine(
                $"public static {asyncString} {returnType} {methodName}_{typeNameWithUnderscore}({typeName} result)");
            builder.AppendLine("{");
            builder.AppendLine($"\tvar factory = {getSpectreFactoryMethodName}();");
            builder.AppendLine($"\treturn {awaitString} factory.{methodName}(result);");
            builder.AppendLine("}");
        }

        builder.AppendLine($"public static {asyncString} {returnType} {methodName}(this {typeName} form)");
        builder.AppendLine("{");
        builder.AppendLine($"\tvar factory = {getSpectreFactoryMethodName}();");
        builder.AppendLine($"\treturn {awaitString} factory.{methodName}(form);");

        builder.AppendLine("}");

        builder.AppendLine($"/// <summary>Asynchronously prompts for the form, observing cancellation.</summary>");
        builder.AppendLine(
            $"public static System.Threading.Tasks.Task<{typeName}> PromptAsync(this {typeName} form, System.Threading.CancellationToken cancellationToken)");
        builder.AppendLine($"    => new {SpectreFactoryClassName}().PromptAsync(form, cancellationToken);");
        if (!IsAsync)
        {
            builder.AppendLine("/// <summary>Asynchronously prompts for the form without cancellation.</summary>");
            builder.AppendLine(
                $"public static System.Threading.Tasks.Task<{typeName}> PromptAsync(this {typeName} form)");
            builder.AppendLine($"    => new {SpectreFactoryClassName}().PromptAsync(form);");
        }

        var asyncFormParameter = CanBeInitializedWithoutParameters ? string.Empty : $"{typeName} result, ";
        var asyncFormArgument = CanBeInitializedWithoutParameters ? $"new {typeName}()" : "result";
        builder.AppendLine(
            "/// <summary>Creates a factory and asynchronously populates the form, observing cancellation.</summary>");
        builder.AppendLine(
            $"public static System.Threading.Tasks.Task<{typeName}> PromptAsync_{typeNameWithUnderscore}({asyncFormParameter}System.Threading.CancellationToken cancellationToken)");
        builder.AppendLine(
            $"    => new {SpectreFactoryClassName}().PromptAsync({asyncFormArgument}, cancellationToken);");
        if (!IsAsync)
        {
            var parameter = CanBeInitializedWithoutParameters ? string.Empty : $"{typeName} result";
            builder.AppendLine(
                "/// <summary>Creates a factory and asynchronously populates the form without cancellation.</summary>");
            builder.AppendLine(
                $"public static System.Threading.Tasks.Task<{typeName}> PromptAsync_{typeNameWithUnderscore}({parameter})");
            builder.AppendLine($"    => new {SpectreFactoryClassName}().PromptAsync({asyncFormArgument});");
        }

        return builder.ToString();
    }
